"""
Export to R, SPSS, and JASP. Takes a CSV of paired labels and writes
a directory with a clean data file and a ready-to-open companion script
for each of those three tools.

I deliberately did not add Parquet or a native SPSS .sav writer. Both
would pull in a heavy binary dependency (pyarrow, pyreadstat) for a
feature very few people will use. Anyone who really needs Parquet can
do it in one line of pandas after loading the CSV I write.
"""

import csv
import os

from .taxonomy import ERROR_TYPES, TAXONOMY


def _category_names(categories, taxonomy=None):
    """category code -> human-readable name, falling back to the code
    itself for custom taxonomies that aren't in `taxonomy` (or the
    built-in TAXONOMY, if none is given)."""
    if taxonomy is None:
        taxonomy = TAXONOMY
    return [taxonomy.get(c, {}).get("name", c) for c in categories]


def _write_csv_copy(rows, csv_path, fieldnames=None):
    if not rows:
        raise ValueError("rows is empty, nothing to export")
    if fieldnames is None:
        fieldnames = list(rows[0].keys())
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)
    return csv_path


def export_for_r(rows, out_path, categories=None, taxonomy=None,
                 label_columns=("human_label", "ai_label")):
    """
    Write out_path (a CSV) plus a companion .R script that reads it back in
    with human_label / ai_label as ordered factors matching the taxonomy in
    effect, and prints the two-line call for Cohen's kappa via the `irr`
    package.

    Args:
        rows (list[dict]): rows to export (item_id, distractor_text,
            human_label, ai_label, ... any extra columns are kept).
        out_path (str): path for the CSV, e.g. "results/coded_items.csv".
            The R script is written alongside it with the same stem and a
            .R extension.
        categories (list[str] | None): defaults to ERROR_TYPES.
        taxonomy (dict | None): a taxonomy dict in the same shape as the
            built-in TAXONOMY constant, for category display names.
            Defaults to the built-in CFI TAXONOMY, pass your own for a
            custom taxonomy (see stats.load_taxonomy_from_json()).
        label_columns (tuple[str]): which columns to set as factors in R.

    Returns:
        dict: {"csv": out_path, "script": <path>.R}
    """
    if categories is None:
        categories = ERROR_TYPES
    csv_path = _write_csv_copy(rows, out_path)
    stem, _ = os.path.splitext(out_path)
    r_path = stem + ".R"

    names = _category_names(categories, taxonomy=taxonomy)
    levels_r = ", ".join(f'"{c}"' for c in categories)
    labels_r = ", ".join(f'"{n}"' for n in names)
    factor_lines = "\n".join(
        f'df${col} <- factor(df${col}, levels = c({levels_r}), labels = c({labels_r}))'
        for col in label_columns
    )

    r_script = f"""# Auto-generated by confusion_mapper.export_for_r(), edit freely, this
# is a starting point, not a locked pipeline.
#
# Reads {os.path.basename(csv_path)} and sets {", ".join(label_columns)}
# as ordered factors matching the taxonomy in effect, then computes Cohen's
# kappa via the `irr` package (install.packages("irr") if needed).

df <- read.csv("{os.path.basename(csv_path)}", stringsAsFactors = FALSE)

{factor_lines}

# --- Cohen's kappa (unweighted / nominal) -----------------------------
if (!requireNamespace("irr", quietly = TRUE)) {{
  install.packages("irr")
}}
library(irr)
kappa_result <- kappa2(df[, c("{label_columns[0]}", "{label_columns[1]}")],
                       weight = "unweighted")
print(kappa_result)

# For Krippendorff's alpha instead:
#   library(irr); kripp.alpha(t(sapply(df[, c("{label_columns[0]}", "{label_columns[1]}")], as.integer)))
"""
    with open(r_path, "w", encoding="utf-8") as f:
        f.write(r_script)

    return {"csv": csv_path, "script": r_path}


def export_for_spss(rows, out_path, categories=None, taxonomy=None,
                    label_columns=("human_label", "ai_label")):
    """
    Write out_path (a CSV) plus a companion .sps syntax file that reads it
    in via GET DATA, applies VALUE LABELS from the taxonomy in effect, and
    points at Analyze > Descriptive Statistics > Crosstabs (Statistics >
    Kappa), the standard SPSS path for Cohen's kappa on two nominal raters.

    A plain-text .sps syntax file is used instead of a binary .sav so this
    package doesn't need a compiled reader/writer dependency; the syntax
    format itself has been stable across SPSS versions for decades.

    Args / Returns: same shape as export_for_r(), plus `taxonomy`.
    """
    if categories is None:
        categories = ERROR_TYPES
    csv_path = _write_csv_copy(rows, out_path)
    stem, _ = os.path.splitext(out_path)
    sps_path = stem + ".sps"

    fieldnames = list(rows[0].keys())
    # SPSS fixed-width VARIABLES clause: give every column a generous
    # string width (A50) except labels, which only need to hold a taxonomy
    # code (A10). Good enough for GET DATA /TYPE=TXT; widen by hand if a
    # column genuinely needs more.
    var_lines = "\n    ".join(
        f"{col} A10" if col in label_columns else f"{col} A200"
        for col in fieldnames
    )
    value_labels = "\n  ".join(
        f"'{c}' '{n}'" for c, n in zip(categories, _category_names(categories, taxonomy=taxonomy))
    )
    label_cols_sps = " ".join(label_columns)

    sps_script = f"""* Auto-generated by confusion_mapper.export_for_spss().
* Reads {os.path.basename(csv_path)} and applies the taxonomy's value labels.

GET DATA /TYPE=TXT
  /FILE="{os.path.basename(csv_path)}"
  /DELCASE=LINE
  /DELIMITERS=","
  /QUALIFIER='"'
  /ARRANGEMENT=DELIMITED
  /FIRSTCASE=2
  /VARIABLES=
    {var_lines}.
CACHE.
EXECUTE.

VALUE LABELS {label_cols_sps}
  {value_labels}.

VARIABLE LABELS
  {label_columns[0]} 'Human rater label'
  {label_columns[1]} 'AI rater label'.

* Cohen's kappa: Analyze > Descriptive Statistics > Crosstabs, put
* {label_columns[0]} and {label_columns[1]} in Row(s)/Column(s), then
* Statistics > check "Kappa".
EXECUTE.
"""
    with open(sps_path, "w", encoding="utf-8") as f:
        f.write(sps_script)

    return {"csv": csv_path, "script": sps_path}


def export_for_jasp(rows, out_path, categories=None, taxonomy=None,
                    label_columns=("human_label", "ai_label")):
    """
    Write out_path (a CSV) plus a short .txt usage note. JASP opens CSV
    files directly (File > Open > Computer / This PC), so there's no
    format conversion to do, the note just points at the right built-in
    analysis (JASP has a dedicated "Cohen's & Fleiss' Kappa" analysis) so
    you don't have to go looking for it.

    Args / Returns: same shape as export_for_r(), plus `taxonomy`.
    """
    if categories is None:
        categories = ERROR_TYPES
    csv_path = _write_csv_copy(rows, out_path)
    stem, _ = os.path.splitext(out_path)
    note_path = stem + "_JASP_INSTRUCTIONS.txt"

    names = _category_names(categories, taxonomy=taxonomy)
    note = f"""Opening this file in JASP
==========================

1. JASP > File > Open > Computer / This PC > {os.path.basename(csv_path)}
   (JASP reads CSV directly, no conversion needed.)

2. Set {label_columns[0]} and {label_columns[1]} to "Nominal" measurement
   type in the variable view if JASP doesn't infer it automatically
   (it usually does, since the values are short text codes).

3. JASP has a built-in "Cohen's & Fleiss' Kappa" analysis. Run it with
   {label_columns[0]} and {label_columns[1]} as the two raters. If your
   JASP version has it filed under a different module than you expect,
   use the analysis search box and type "kappa", module locations have
   moved between JASP releases, the analysis itself has been present
   since JASP added it (GitHub jasp-stats/jasp-issues #310, #1476).

4. Category codes in this file: {", ".join(f"{c} = {n}" for c, n in zip(categories, names))}.
"""
    with open(note_path, "w", encoding="utf-8") as f:
        f.write(note)

    return {"csv": csv_path, "instructions": note_path}


def export_all(rows, out_dir, stem="confusion_mapper_export", categories=None,
               taxonomy=None, formats=("r", "spss", "jasp")):
    """
    Convenience wrapper: run export_for_r / export_for_spss / export_for_jasp
    in one call, all writing into out_dir with the same base filename.

    Args:
        rows (list[dict])
        out_dir (str): created if it doesn't exist.
        stem (str): base filename, no extension.
        categories (list[str] | None)
        taxonomy (dict | None): see export_for_r(), pass your own for a
            custom (non-CFI) taxonomy.
        formats (tuple[str]): any of "r", "spss", "jasp".

    Returns:
        dict: {"r": {...} | None, "spss": {...} | None, "jasp": {...} | None}
    """
    os.makedirs(out_dir, exist_ok=True)
    base = os.path.join(out_dir, stem + ".csv")

    result = {"r": None, "spss": None, "jasp": None}
    if "r" in formats:
        result["r"] = export_for_r(rows, base, categories=categories, taxonomy=taxonomy)
    if "spss" in formats:
        result["spss"] = export_for_spss(rows, base, categories=categories, taxonomy=taxonomy)
    if "jasp" in formats:
        result["jasp"] = export_for_jasp(rows, base, categories=categories, taxonomy=taxonomy)
    return result
